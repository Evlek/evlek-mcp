#!/usr/bin/env node
// Brings this repo's live-derived files up to the hosted server
// (https://evlek.app/api/mcp): tools.json (byte-identical to the live
// `tools/list`, same 2-space projection `pnpm mcp:export-public` writes), the
// version in server.json / package.json / package-lock.json / README status,
// the README tools table, and the `ui://` widget URIs in README.
//
// TOOLS.md and CHANGELOG.md are NOT touched: TOOLS.md comes only from the
// source repo's export, and a changelog entry needs a human.
//
// Writes a summary to $GITHUB_STEP_SUMMARY (when set) and prints
// `changed=true|false` to $GITHUB_OUTPUT so the live-sync workflow knows
// whether to open a PR. Exit 0 on success, 1 when the live server can't be
// read (never writes a half-updated repo).
//
// Usage: node scripts/sync-from-live.mjs [endpoint]
import { readFileSync, writeFileSync, appendFileSync } from 'node:fs';

const ENDPOINT = process.argv[2] || 'https://evlek.app/api/mcp';

async function rpc(id, method, params = {}) {
    const res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream' },
        body: JSON.stringify({ jsonrpc: '2.0', id, method, params }),
        signal: AbortSignal.timeout(30_000),
    });
    if (!res.ok) throw new Error(`${method}: HTTP ${res.status}`);
    let text = await res.text();
    // Streamable HTTP may answer as SSE; take the data lines.
    if (!text.trimStart().startsWith('{')) {
        text = text.split('\n').filter((l) => l.startsWith('data:')).map((l) => l.slice(5)).join('');
    }
    const json = JSON.parse(text);
    if (json.error) throw new Error(`${method}: ${json.error.message}`);
    return json.result;
}

function read(path) {
    return readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
}

function writeIfChanged(path, next, changes) {
    if (read(path) !== next) {
        writeFileSync(path, next, 'utf8');
        changes.push(path);
    }
}

const init = await rpc(1, 'initialize', {
    protocolVersion: '2025-06-18',
    capabilities: {},
    clientInfo: { name: 'evlek-mcp-live-sync', version: '1' },
});
const { tools } = await rpc(2, 'tools/list');
const { resources } = await rpc(3, 'resources/list');
const liveVersion = init.serverInfo?.version;
if (!liveVersion || !Array.isArray(tools) || tools.length === 0) {
    console.error('✗ Live server answered without a version or tools — nothing written.');
    process.exit(1);
}

const changes = [];
const repoVersion = JSON.parse(read('server.json')).version;

// tools.json — same bytes as the export: JSON.stringify(tools, null, 2) + "\n".
writeIfChanged('tools.json', JSON.stringify(tools, null, 2) + '\n', changes);

// Versions. Only the "version" field is touched, so the registry shape of
// server.json (README "Sözleşme dosyaları") is kept.
const setVersion = (text) => text.replace(/("version":\s*")[^"]+(")/, `$1${liveVersion}$2`);
writeIfChanged('server.json', setVersion(read('server.json')), changes);
writeIfChanged('package.json', setVersion(read('package.json')), changes);
const lock = JSON.parse(read('package-lock.json'));
lock.version = liveVersion;
if (lock.packages?.['']) lock.packages[''].version = liveVersion;
writeIfChanged('package-lock.json', JSON.stringify(lock, null, 2) + '\n', changes);

// README: tools table (same rows as the export's README-tools-table.md),
// widget URIs from the live resources/list, and the status version.
let readme = read('README.md');
const rows = tools.map((t) => `| \`${t.name}\` | ${t.title} | ${t.description.replace(/\|/g, '\\|')} |`).join('\n');
readme = readme.replace(
    /(<!-- AUTO-GENERATED by `pnpm mcp:export-public`[^\n]*\n\n\*\*)\d+( tools\*\*[^\n]*\n\n\| Tool \| Title \| Description \|\n\|[-|]+\|\n)[\s\S]*?(\n\n<!-- \/AUTO-GENERATED -->)/,
    (_, a, b, c) => `${a}${tools.length}${b}${rows}${c}`,
);
for (const { uri } of resources.filter((r) => r.uri.startsWith('ui://'))) {
    const m = uri.match(/^(ui:\/\/evlek\/[a-z-]+?-v\d+)(?:-\d+)?\.html$/);
    if (m) readme = readme.replace(new RegExp(`${m[1].replace(/[/.]/g, '\\$&')}(?:-\\d+)?\\.html`, 'g'), uri);
}
readme = readme.replace(/(\*\*MCP version:\*\* )[^ ]+( \(live\))/, `$1${liveVersion}$2`);
writeIfChanged('README.md', readme, changes);

const summary = [
    `Live server: **${liveVersion}** (repo: ${repoVersion}), ${tools.length} tools.`,
    changes.length ? `Updated: ${changes.map((c) => `\`${c}\``).join(', ')}` : 'No difference from the live server.',
].join('\n\n');
console.log(summary);
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary + '\n');
if (process.env.GITHUB_OUTPUT) {
    appendFileSync(
        process.env.GITHUB_OUTPUT,
        `changed=${changes.length > 0}\nlive_version=${liveVersion}\nrepo_version=${repoVersion}\n`,
    );
}
